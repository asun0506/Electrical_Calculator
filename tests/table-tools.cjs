const assert=require('node:assert/strict');
const C=require('../js/table-tools-core.js');
const s=C.defaults();
assert.equal(C.presets.length,10);
assert.equal(C.presets.find(p=>p.id==='p18-review').headerFill,'#b8e8eb');
assert.equal(C.presets.find(p=>p.id==='p18-navy').headerFill,'#00243b');
const resized=C.resize(s,3,2);
assert.equal(resized.cells.length,3);assert.equal(resized.cells[0].length,2);
assert.equal(s.cells.length,5,'resizing never mutates source');
assert.throws(()=>C.normalize({...s,width:0}),/宽度/);
assert.throws(()=>C.normalize({...s,cells:[['A','B'],['bad']]}),/行列/);
assert.throws(()=>C.normalize({...s,overrides:{'90:0':{fill:'#ffffff'}}}),/单元格/);
const html=C.toHTML({...s,cells:s.cells.map((r,i)=>r.map((v,c)=>i===1&&c===0?'<img src=x onerror=alert(1)>':v))});
assert.ok(html.includes('&lt;img'));assert.ok(!html.includes('<img'));
assert.ok(!html.includes('<textarea'));
const selected={...s,overrides:{'1:0':{fill:'#ff0000',color:'#ffffff',bold:true}}};
assert.equal(C.cellStyle(selected,1,0).fill,'#ff0000');
assert.ok(C.toHTML(selected).includes('background-color:#ff0000'));
const files=C.pptxFiles(selected);
assert.match(files['ppt/slides/slide1.xml'],/<a:tbl>/);
assert.match(files['ppt/slides/slide1.xml'],/uri="http:\/\/schemas.openxmlformats.org\/drawingml\/2006\/table"/);
assert.match(files['ppt/slides/slide1.xml'],/FF0000/);
assert.ok(!files['ppt/slides/slide1.xml'].includes('<p:pic>'),'PPT contains a native editable table');
assert.match(files['[Content_Types].xml'],/presentationml.presentation.main/);
const longTable=C.resize(s,50,4),longFiles=C.pptxFiles(longTable);
const slides=Object.keys(longFiles).filter(key=>/^ppt\/slides\/slide\d+\.xml$/.test(key));
assert.ok(slides.length>1,'long tables split over multiple slides');
slides.forEach(key=>assert.match(longFiles[key],/项目/,'header is repeated on each slide'));
const noHeader=C.pptxFiles({...longTable,header:false});
assert.ok(Object.keys(noHeader).filter(key=>/^ppt\/slides\/slide\d+\.xml$/.test(key)).length>1);
console.log('PASS table presets, dimensions, non-mutating resize, safe HTML, cell formatting and editable PPTX');
