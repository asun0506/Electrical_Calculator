const assert = require('node:assert/strict'), path = require('node:path');
const { pathToFileURL } = require('node:url'), { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--allow-file-access-from-files'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }), prompts = [], errors = [];
    let acceptDelete = false;
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => { prompts.push(dialog.message()); return acceptDelete ? dialog.accept() : dialog.dismiss(); });
    await page.goto(pathToFileURL(path.join(__dirname, '..', 'index.html')).href);
    await page.evaluate(() => ElectricalToolkit.open('precharge'));
    await page.locator('#pc-v').fill('711'); await page.evaluate(() => ElectricalProjectController.flush());
    const a = await page.locator('[data-project-select]').inputValue();
    const before = await page.evaluate(() => ElectricalProjectController.workspace());
    await page.locator('[data-project-action=manage]').click();
    assert.deepEqual(prompts, [], 'opening management must never prompt to delete');
    assert.equal(await page.locator('dialog.project-manager[open]').count(), 1, 'management opens a project list');
    assert.equal(await page.locator('[data-managed-id]').count(), 1);
    assert.equal(await page.locator('[data-managed-action=delete]').isDisabled(), true, 'last project cannot be deleted');
    assert.deepEqual(await page.evaluate(() => ElectricalProjectController.workspace()), before, 'opening management is read-only');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-project-action=manage]').evaluate(node => node === document.activeElement), true);
    await page.evaluate(() => ElectricalProjectController.newProject('B')); const b = await page.locator('[data-project-select]').inputValue();
    await page.locator('#pc-v').fill('522'); await page.evaluate(() => ElectricalProjectController.flush());
    await page.locator('[data-project-action=manage]').click();
    const row = id => page.locator(`[data-managed-id="${id}"]`);
    if (process.env.PROJECT_MANAGER_QA) {
      await page.screenshot({ path: path.join(process.env.PROJECT_MANAGER_QA, 'project-manager-desktop.png') });
      await page.setViewportSize({ width: 390, height: 844 });
      assert.equal(await page.locator('dialog.project-manager').evaluate(node => node.scrollWidth <= node.clientWidth + 1), true, 'narrow management dialog must not overflow horizontally');
      await page.screenshot({ path: path.join(process.env.PROJECT_MANAGER_QA, 'project-manager-mobile.png') });
      await page.setViewportSize({ width: 1440, height: 1000 });
    }
    await row(a).locator('[data-managed-action=rename]').click();
    await page.locator('dialog input[name=projectName]').fill('A <安全>');
    await page.locator('dialog form button[type=submit]').click();
    await page.waitForFunction(id => ElectricalProjectController.projects().find(p => p.id === id)?.name === 'A <安全>', a);
    assert.equal(await page.locator('[data-project-select]').inputValue(), b, 'renaming another project must not switch the active editor');
    assert.equal(await page.locator('#pc-v').inputValue(), '522');
    await row(a).locator('[data-managed-action=open]').click();
    await page.waitForFunction(() => document.querySelector('#pc-v')?.value === '711');
    await row(a).locator('[data-managed-action=copy]').click();
    await page.locator('dialog input[name=projectName]').fill('A 副本'); await page.locator('dialog form button[type=submit]').click();
    await page.waitForFunction(() => ElectricalProjectController.projects().length === 3);
    const copy = await page.locator('[data-project-select]').inputValue(); assert.notEqual(copy, a);
    assert.equal(await page.locator('#pc-v').inputValue(), '711');
    await row(b).locator('[data-managed-action=delete]').click();
    assert.equal(await page.locator('[data-managed-id]').count(), 3, 'cancel delete preserves every project');
    assert.match(prompts.at(-1), /B/);
    acceptDelete = true; await row(b).locator('[data-managed-action=delete]').click();
    await page.waitForFunction(() => ElectricalProjectController.projects().length === 2);
    assert.equal(await row(b).count(), 0);
    await row(copy).locator('[data-managed-action=delete]').click();
    await page.waitForFunction(() => ElectricalProjectController.projects().length === 1);
    assert.equal(await page.locator('[data-managed-action=delete]').isDisabled(), true);
    assert.equal(await page.locator('#pc-v').inputValue(), '711');
    await page.locator('[data-close-manager]').click(); await page.reload(); await page.waitForSelector('#pc-v');
    assert.equal(await page.locator('#pc-v').inputValue(), '711');
    await page.evaluate(() => ElectricalProjectController.newProject('失败保护测试'));
    await page.locator('#pc-v').fill('712');
    await page.locator('[data-project-action=manage]').click();
    const retained = await page.evaluate(() => ElectricalProjectController.workspace());
    await page.evaluate(() => { Storage.prototype.setItem = () => { throw Error('quota'); }; IDBObjectStore.prototype.put = () => { throw Error('quota'); }; });
    await row(a).locator('[data-managed-action=delete]').click();
    await page.waitForFunction(() => document.querySelector('[data-manager-status]')?.textContent.includes('操作未完成'));
    assert.deepEqual(await page.evaluate(() => ElectricalProjectController.workspace()), retained, 'failed save blocks delete and preserves all projects');
    assert.equal(await page.locator('#pc-v').inputValue(), '712');
    assert.deepEqual(errors, []);
    console.log('PASS project management: read-only open, list, scoped rename/switch/copy, confirmed delete, cancel, last-project protection and reload');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
