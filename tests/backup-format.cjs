const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const { createHash } = require('node:crypto');
const target = path.join(__dirname, '../js/backup-format.js');
assert.ok(fs.existsSync(target), 'backup format must produce verified portable snapshots');
const F = require(target), C = require('../js/workspace-core.js');
const digest = async value => createHash('sha256').update(value).digest('hex');
const png = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=';
const payload = { form: [{ id: 'image-source', index: 0, value: png }], model: { image: { dataUrl: png }, second: { dataUrl: png } }, tabs: [], details: [] };
const state = C.createProject(C.createWorkspace(), { moduleId: 'bolt', name: 'CON', payload, appVersion: '2.1.1', adapterVersion: 1 }, { id: 'sample', now: '2026-10-22T00:00:00Z' }).value;
const snapshot = { formatVersion: 1, id: 'snapshot-1', createdAt: '2026-10-22T00:00:00Z', appVersion: '2.1.1', workspaceRevision: 1, projects: state.projects, queries: {}, shared: { materials: { customs: {}, overrides: {} } }, preserved: [], browserUnsaved: false };
const adapters = new Map([['bolt', { version: 1, validate: C.validatePayload }]]);
(async () => {
  const packed = await F.pack(snapshot, { digest, modules: { bolt: '螺栓校核' } });
  assert.equal(packed.ok, true);
  assert.ok(packed.value.files.has('manifest.json'));
  assert.ok(packed.value.files.has('complete.json'));
  assert.equal([...packed.value.files.keys()].filter(key => key.includes('/attachments/')).length, 1, 'same attachment bytes stored once');
  assert.ok([...packed.value.files.keys()].some(key => key.includes('_CON__sample')), 'Windows reserved project names safe');
  const inspection = await F.inspect(packed.value.files, { digest, adapters });
  assert.equal(inspection.ok, true);
  assert.deepEqual(inspection.value.validProjects[0].payload, payload, 'model and duplicate form attachment reconstruct exactly');
  assert.equal(inspection.value.invalidProjects.length, 0);
  assert.deepEqual(snapshot.projects[0].payload, payload, 'packing never mutates live snapshot');
  const corrupt = new Map(packed.value.files);
  const asset = [...corrupt.keys()].find(key => key.includes('/attachments/'));
  corrupt.set(asset, new Uint8Array([1, 2, 3]));
  const corruptInspection = await F.inspect(corrupt, { digest, adapters });
  assert.equal(corruptInspection.ok, true);
  assert.equal(corruptInspection.value.validProjects.length, 0);
  assert.equal(corruptInspection.value.invalidProjects.length, 1, 'corrupt independent project not restored');
  const unfinished = new Map(packed.value.files); unfinished.delete('complete.json');
  assert.equal((await F.inspect(unfinished, { digest, adapters })).ok, false);
  for (const key of ['../x', '/root', 'C:/x', '\\host\\x', 'a\\b', './x', 'a//b', 'a/../b', 'a/./b']) assert.equal(F.safeRelativePath(key), false, key);
  const traversal = new Map(packed.value.files); traversal.set('../bad', new Uint8Array([0]));
  assert.equal((await F.inspect(traversal, { digest, adapters })).ok, false);
  const collisions = new Map(packed.value.files); collisions.set('MANIFEST.JSON', new Uint8Array([0]));
  assert.equal((await F.inspect(collisions, { digest, adapters })).ok, false);
  const future = { ...snapshot, formatVersion: 9 };
  assert.equal((await F.pack(future, { digest })).ok, false);
  console.log('PASS backup format: manifest/completion, SHA-256, deduplicated attachments, safe names/paths, exact roundtrip and corrupt project quarantine');
})().catch(error => { console.error(error); process.exitCode = 1; });
